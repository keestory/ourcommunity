import { test, expect } from '@playwright/test'

test.beforeEach(async ({ request }) => {
  const health = await request.get('/api/health')
  expect(health.ok()).toBeTruthy()
  expect((await health.json()).preview?.enabled).toBe(true)
})

test('unknown session mode fails closed without credential inputs', async ({ page }) => {
  await page.route('**/api/session', route => route.fulfill({ status: 429, contentType: 'application/json', body: JSON.stringify({ detail: '체험 공간이 잠시 붐비고 있어요.' }) }))
  await page.goto('/auth')
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByLabel('비밀번호', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '처음이에요 · 로컬 계정 만들기' })).toHaveCount(0)
  await page.unroute('**/api/session')
  await page.getByRole('button', { name: '다시 시도' }).click()
  await expect(page.getByText('가상 역할 선택 · 실제 계정 로그인이 아니에요')).toBeVisible()
})

test('isolated mobile preview: chat, RSVP, role change, attendance and reload', async ({ page, browser }) => {
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  await page.goto('/groups/hangang/chat')
  await expect(page.getByText('체험 전용 · 가상 데이터입니다.', { exact: false })).toBeVisible()
  await expect(page.getByLabel('비밀번호', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '멤버로 둘러보기' }).click()
  await expect(page.getByRole('heading', { name: '오늘의 이야기를 나눠요.' })).toBeVisible()
  const message = `브라우저 독립 체험 ${Date.now()}`
  await page.getByRole('textbox', { name: '메시지', exact: true }).fill(message)
  await page.getByRole('button', { name: '메시지 보내기' }).click()
  await expect(page.getByText(message, { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText(message, { exact: true })).toBeVisible()
  const events = await page.request.get('/api/groups/hangang/events').then(response => response.json())
  const upcoming = events.items.find((event: { can_mark_attendance: boolean; title: string }) => event.title.includes('토요일'))
  await page.goto(`/groups/hangang/events/${upcoming.id}`)
  await page.getByRole('button', { name: '참가 신청', exact: true }).click()
  await expect(page.getByText('모임에서 만나요!', { exact: true })).toBeVisible()
  const joined = await page.request.get(`/api/events/${upcoming.id}`).then(response => response.json())
  expect(joined.my_status).toBe('confirmed')
  await page.getByRole('button', { name: '계정과 로그아웃' }).click()
  await page.getByRole('button', { name: '역할 다시 선택' }).click()
  await page.getByRole('button', { name: '운영자로 둘러보기' }).click()
  await expect(page.getByRole('heading', { name: upcoming.title, exact: true })).toBeVisible()
  const beforeResponse = await page.request.get('/api/groups/hangang/growth')
  expect(beforeResponse.ok()).toBeTruthy()
  const before = await beforeResponse.json()
  const past = events.items.find((event: { title: string }) => event.title.includes('지난 모임'))
  await page.goto(`/groups/hangang/events/${past.id}`)
  const jiho = page.locator('.member-row').filter({ has: page.getByText('지호', { exact: true }) })
  await jiho.getByRole('button', { name: '출석 확인', exact: true }).click()
  await expect(jiho.getByRole('button', { name: '출석 수정', exact: true })).toBeVisible()
  const after = await page.request.get('/api/groups/hangang/growth').then(response => response.json())
  expect(after.total_contributions).toBe(before.total_contributions + 1)
  await page.goto('/groups/hangang/memories')
  await expect(page.getByRole('heading', { name: '우리의 작은 기념물.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/preview-mobile-memories.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/groups/hangang/space')
  await expect(page.getByRole('heading', { name: '한강 새벽 러너스.' })).toBeVisible()
  await page.screenshot({ path: 'test-results/preview-desktop-space.png', fullPage: true })
  await page.goto('/groups/hangang/settings')
  await expect(page.getByRole('button', { name: '초대 링크 만들기' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '비공개', exact: true })).toBeDisabled()
  const other = await browser.newContext({ baseURL: test.info().project.use.baseURL })
  const otherPage = await other.newPage()
  await otherPage.goto('/groups/hangang/chat')
  await otherPage.getByRole('button', { name: '멤버로 둘러보기' }).click()
  await expect(otherPage.getByRole('heading', { name: '오늘의 이야기를 나눠요.' })).toBeVisible()
  await expect(otherPage.getByText(message, { exact: true })).toHaveCount(0)
  await other.close()
  expect(failures).toEqual([])
})
